// Transcribes clips with ElevenLabs Speech to Text (word-level timestamps) and saves
// web/lib/transcripts/<clip-id>.json, then regenerates web/lib/transcripts/manifest.ts with each
// transcript's sha256 (the hash shown on license certificates).
//
// Run from web/:
//   npm run transcribe -- clip-4 clip-5      transcribe these clips
//   npm run transcribe -- --all              every clip in lib/clips.json
//   npm run transcribe -- --manifest         only rebuild manifest.ts from the JSON files
//   npm run transcribe -- clip-7 --keyterms Snippet,SpaceLofi   bias recognition toward these words
//                                            (ElevenLabs keyterms; recorded in the transcript file)
//
// It sends the ORIGINAL master (public/<videoUrl>, the file whose sha256 is the clip's on-chain fileHash),
// never the preview, and refuses if the file doesn't match clips.json.
// Needs ELEVENLABS_API_KEY in web/.env.local (server only). The key is never printed.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { basename } from "node:path";

const MODEL_ID = "scribe_v2";
const API_URL = "https://api.elevenlabs.io/v1/speech-to-text";
const OUT_DIR = new URL("../lib/transcripts/", import.meta.url);

const sha256 = (bytes) => "0x" + createHash("sha256").update(bytes).digest("hex");

function apiKey() {
  if (process.env.ELEVENLABS_API_KEY) return process.env.ELEVENLABS_API_KEY;
  const envFile = new URL("../.env.local", import.meta.url);
  if (existsSync(envFile)) {
    for (const line of readFileSync(envFile, "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*ELEVENLABS_API_KEY\s*=\s*(.*)\s*$/);
      if (m) return m[1].replace(/^["']|["']$/g, "");
    }
  }
  throw new Error("ELEVENLABS_API_KEY is not set (add it to web/.env.local)");
}

async function transcribe(clip, key, keyterms = []) {
  const file = readFileSync(new URL(`../public${clip.videoUrl}`, import.meta.url));
  const fileHash = sha256(file);
  if (fileHash !== clip.fileHash) {
    throw new Error(`${clip.id}: ${clip.videoUrl} is not the master in clips.json (sha256 ${fileHash})`);
  }

  const form = new FormData();
  form.append("model_id", MODEL_ID);
  form.append("file", new Blob([file], { type: "video/mp4" }), basename(clip.videoUrl));
  form.append("timestamps_granularity", "word");
  form.append("tag_audio_events", "true");
  form.append("diarize", "false");
  for (const term of keyterms) form.append("keyterms", term);

  const res = await fetch(API_URL, { method: "POST", headers: { "xi-api-key": key }, body: form });
  if (!res.ok) {
    const body = (await res.text()).slice(0, 500);
    // A video with no audio track at all (e.g. the nature clips) has nothing to transcribe: no file is written,
    // and the site shows no captions or transcript for it.
    if (res.status === 400 && body.includes('"invalid_audio"')) {
      console.log(`${clip.id}: skipped, the file has no playable audio track`);
      return;
    }
    throw new Error(`${clip.id}: ElevenLabs returned ${res.status}: ${body}`);
  }
  const stt = await res.json();

  // Keep spoken words and tagged audio events; "spacing" entries are just the gaps between words.
  const words = (stt.words ?? [])
    .filter((w) => w.type === "word" || w.type === "audio_event")
    .map((w) => ({ text: w.text, start: w.start, end: w.end, type: w.type }));

  const transcript = {
    clipId: clip.id,
    fileHash, // sha256 of the master that was transcribed (same as the on-chain fileHash)
    model: MODEL_ID,
    ...(keyterms.length ? { keyterms } : {}),
    language: stt.language_code ?? null,
    languageProbability: stt.language_probability ?? null,
    hasSpeech: words.some((w) => w.type === "word"),
    text: (stt.text ?? "").trim(),
    words,
  };

  // Deterministic bytes (LF, 2-space indent, trailing newline) so the sha256 is reproducible.
  const json = JSON.stringify(transcript, null, 2) + "\n";
  writeFileSync(new URL(`${clip.id}.json`, OUT_DIR), json);
  console.log(
    `${clip.id}: ${transcript.hasSpeech ? `"${transcript.text}"` : "(no speech)"} ` +
      `[${transcript.language}, ${words.length} words/events] sha256 ${sha256(json)}`,
  );
}

// manifest.ts imports every transcript JSON statically (the pages are client components) and records
// the sha256 of each file's exact bytes.
function writeManifest() {
  const files = readdirSync(OUT_DIR)
    .filter((f) => f.endsWith(".json"))
    .sort();
  const imports = files.map((f, i) => `import t${i} from "./${f}";`);
  const entries = files.map((f, i) => {
    const hash = sha256(readFileSync(new URL(f, OUT_DIR)));
    return `  ${JSON.stringify(f.replace(/\.json$/, ""))}: { sha256: "${hash}", transcript: t${i} as Transcript },`;
  });
  const ts = [
    "// Generated by scripts/transcribe.mjs. Do not edit by hand: run `npm run transcribe -- --manifest`.",
    "// sha256 is the hash of the transcript JSON file's exact bytes (`sha256sum lib/transcripts/<clip-id>.json`).",
    'import type { Transcript } from "../captions";',
    ...imports,
    "",
    "export const TRANSCRIPTS: Record<string, { sha256: `0x${string}`; transcript: Transcript }> = {",
    ...entries,
    "};",
    "",
  ].join("\n");
  writeFileSync(new URL("manifest.ts", OUT_DIR), ts);
  console.log(`manifest.ts: ${files.length} transcript(s)`);
}

const rawArgs = process.argv.slice(2);
const ktIndex = rawArgs.indexOf("--keyterms");
const keyterms = ktIndex >= 0 ? (rawArgs[ktIndex + 1] ?? "").split(",").map((t) => t.trim()).filter(Boolean) : [];
const args = ktIndex >= 0 ? rawArgs.filter((_, i) => i !== ktIndex && i !== ktIndex + 1) : rawArgs;
mkdirSync(OUT_DIR, { recursive: true });

if (!args.includes("--manifest")) {
  const { clips } = JSON.parse(readFileSync(new URL("../lib/clips.json", import.meta.url), "utf8"));
  const ids = args.includes("--all") ? clips.map((c) => c.id) : args.filter((a) => !a.startsWith("--"));
  if (ids.length === 0) {
    console.error("Usage: npm run transcribe -- <clip-id>... | --all | --manifest");
    process.exit(1);
  }
  const key = apiKey();
  for (const id of ids) {
    const clip = clips.find((c) => c.id === id);
    if (!clip) throw new Error(`${id}: not in lib/clips.json`);
    await transcribe(clip, key, keyterms);
  }
}
writeManifest();
